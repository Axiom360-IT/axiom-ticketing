import { type ExportDataset } from "@/lib/export/dataset";
import type {
  CsatStats,
  ProcurementSpend,
  ReportRange,
  TicketHealth,
} from "@/lib/reports/queries";

// The shape of the management report, in ONE place.
//
// Both the on-demand download (/api/reports/export) and the scheduled email
// report build from this, so what lands in the IT Director's inbox at 19:00 is
// the same document someone else gets by clicking Export. When the two drift,
// people stop trusting both.

const usd = new Intl.NumberFormat("en-US", {
  style: "currency",
  currency: "USD",
});

function pct(rate: number | null): string {
  return rate === null ? "—" : `${(rate * 100).toFixed(1)}%`;
}

function dayStr(d: Date): string {
  return d.toISOString().slice(0, 10);
}

export function buildReportDataset(
  tickets: TicketHealth,
  procurement: ProcurementSpend,
  csat: CsatStats,
  generatedBy: string,
  range?: ReportRange,
): ExportDataset {
  const now = new Date();
  const scope = range
    ? `All organizations · ${dayStr(range.from)} to ${dayStr(range.to)}`
    : "All organizations, all time";

  // With a period selected the rolling-window figures don't apply — show a
  // single "in period" total instead of the 7-day / 30-day / all-time split.
  const ticketTotals = range
    ? [{ label: "Created (in period)", value: String(tickets.totalsByWindow.allTime) }]
    : [
        { label: "Created (last 7 days)", value: String(tickets.totalsByWindow.week) },
        { label: "Created (last 30 days)", value: String(tickets.totalsByWindow.month) },
        { label: "Total (all time)", value: String(tickets.totalsByWindow.allTime) },
      ];

  return {
    title: "IT Operations Report",
    subtitle: range
      ? `Ticket health & procurement spend · ${dayStr(range.from)} – ${dayStr(range.to)}`
      : "Ticket health & procurement spend",
    meta: [
      { label: "Generated by", value: generatedBy },
      {
        label: "Generated at",
        value: `${now.toISOString().slice(0, 16).replace("T", " ")} UTC`,
      },
      { label: "Scope", value: scope },
    ],
    sections: [
      {
        kind: "keyValues",
        title: "Ticket health",
        items: [
          ...ticketTotals,
          {
            label: "Average resolution",
            value:
              tickets.averageResolutionMinutes !== null
                ? `${tickets.averageResolutionMinutes} min`
                : "—",
          },
          { label: "CSAT rate", value: pct(tickets.csatRate.rate) },
          {
            label: "CSAT responses",
            value: `${tickets.csatRate.satisfied} satisfied · ${tickets.csatRate.unsatisfied} unsatisfied`,
          },
          { label: "Escalation rate", value: pct(tickets.escalationRate) },
          { label: "SLA compliance", value: pct(tickets.slaComplianceRate) },
        ],
      },
      {
        kind: "table",
        title: "Tickets by status",
        columns: ["Status", "Count"],
        align: ["left", "right"],
        rows: tickets.byStatus.map((r) => [r.status, r.count]),
      },
      {
        kind: "table",
        title: "Tickets by stream",
        columns: ["Stream", "Count"],
        align: ["left", "right"],
        rows: tickets.byStream.map((r) => [r.stream, r.count]),
      },
      {
        kind: "table",
        title: "Technician load",
        columns: ["Technician", "Assigned", "Resolved"],
        align: ["left", "right", "right"],
        rows: tickets.techLoad.map((r) => [r.name, r.assigned, r.resolved]),
      },
      {
        kind: "keyValues",
        title: "Customer satisfaction",
        items: [
          { label: "Positive (happy)", value: pct(csat.breakdown.positiveRate) },
          {
            label: "Responses",
            value: `${csat.breakdown.happy} happy · ${csat.breakdown.neutral} okay · ${csat.breakdown.unhappy} unhappy`,
          },
          {
            label: "First-contact happy",
            value: pct(csat.quality.firstContactRate),
          },
          { label: "Rework rate", value: pct(csat.quality.reworkRate) },
        ],
      },
      {
        kind: "table",
        title: "CSAT by technician",
        columns: ["Technician", "Happy", "Okay", "Unhappy", "Positive"],
        align: ["left", "right", "right", "right", "right"],
        rows: csat.byTechnician.map((r) => [
          r.technicianName ?? "Unassigned",
          r.happy,
          r.neutral,
          r.unhappy,
          pct(r.positiveRate),
        ]),
      },
      {
        kind: "table",
        title: "CSAT by organization",
        columns: ["Organization", "Happy", "Okay", "Unhappy", "Positive"],
        align: ["left", "right", "right", "right", "right"],
        rows: csat.byOrganization.map((r) => [
          r.organizationName ?? "No organization",
          r.happy,
          r.neutral,
          r.unhappy,
          pct(r.positiveRate),
        ]),
      },
      {
        kind: "keyValues",
        title: "Procurement spend",
        items: [
          ...(range
            ? [
                {
                  label: "Spend (in period)",
                  value: usd.format(procurement.totalsByWindow.year),
                },
              ]
            : [
                { label: "Last 30 days", value: usd.format(procurement.totalsByWindow.month) },
                { label: "Last 90 days", value: usd.format(procurement.totalsByWindow.quarter) },
                { label: "Last 12 months", value: usd.format(procurement.totalsByWindow.year) },
              ]),
          {
            label: "Pending",
            value: `${procurement.pendingApprovals.count} request(s) · ${usd.format(procurement.pendingApprovals.total)}`,
          },
        ],
      },
      {
        kind: "table",
        title: "Procurement by type",
        columns: ["Type", "Total"],
        align: ["left", "right"],
        rows: procurement.byType.map((r) => [r.type, usd.format(r.total)]),
      },
      {
        kind: "table",
        title: "Procurement by stage",
        columns: ["Stage", "Count", "Total"],
        align: ["left", "right", "right"],
        rows: procurement.byStatus.map((r) => [r.status, r.count, usd.format(r.total)]),
      },
      {
        kind: "table",
        title: "Top procurement items",
        columns: ["Item", "Total"],
        align: ["left", "right"],
        rows: procurement.topItems.map((r) => [r.itemName, usd.format(r.total)]),
      },
    ],
  };
}
